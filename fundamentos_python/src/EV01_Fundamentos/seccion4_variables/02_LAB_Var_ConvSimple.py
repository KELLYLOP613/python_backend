kilometers = 12.25
miles = 7.38

miles_to_kilometers = miles * 1.61 # se realiza conversión teniendo en cuenta que 1 milla equivale a 1.61 km
kilometers_to_miles = kilometers / 1.61 # se realiza conversión teniendo en cuenta que 1 milla equivale a 1.61 km

print(miles, "millas son", round(miles_to_kilometers, 2), "kilómetros")
print(kilometers, "kilómetros son", round(kilometers_to_miles, 2), "millas")

